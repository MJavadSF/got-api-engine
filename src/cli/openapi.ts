/**
 * OpenAPI 3.x → TypeScript endpoint definitions (also the got-api-engine-codegen CLI).
 *
 * @packageDocumentation
 * @module got-api-engine/codegen
 */
// ── OpenAPI 3.x (JSON) → typed endpoint definitions ──────────────
//
// Emits TypeScript types for `components.schemas` and one
// `EndpointDefinition` per operation. Bind them with
// `const client = api.endpoints(endpoints)`.

/** A parsed OpenAPI document (or any JSON object inside it). */
export type OpenApiDocument = Record<string, unknown>;

interface Operation {
  operationId?: string;
  summary?: string;
  parameters?: OpenApiDocument[];
  requestBody?: OpenApiDocument;
  responses?: Record<string, OpenApiDocument>;
}

const METHODS = ["get", "post", "put", "patch", "delete", "head", "options", "query"] as const;
const IDENT = /^[A-Za-z_$][\w$]*$/;

const pascal = (s: string): string =>
  s
    .replace(/[^A-Za-z0-9]+(.)?/g, (_m, c: string | undefined) => (c ? c.toUpperCase() : ""))
    .replace(/^[a-z]/, (c) => c.toUpperCase())
    .replace(/^(\d)/, "_$1");
const camel = (s: string): string => pascal(s).replace(/^[A-Z]/, (c) => c.toLowerCase());
const prop = (name: string): string => (IDENT.test(name) ? name : JSON.stringify(name));

export class SchemaPrinter {
  constructor(private readonly root: OpenApiDocument) {}

  private resolveRef(ref: string): string {
    const name = ref.split("/").pop() ?? "Unknown";
    return pascal(decodeURIComponent(name.replace(/~1/g, "/").replace(/~0/g, "~")));
  }

  print(schema: unknown, depth = 0): string {
    if (!schema || typeof schema !== "object" || depth > 20) return "unknown";
    const s = schema as OpenApiDocument;
    if (typeof s["$ref"] === "string") return this.resolveRef(s["$ref"]);

    const nullable = s["nullable"] === true;
    const wrap = (t: string): string => (nullable ? `${t} | null` : t);

    if ("const" in s) return wrap(JSON.stringify(s["const"]));
    if (Array.isArray(s["enum"])) return wrap((s["enum"] as unknown[]).map((v) => JSON.stringify(v)).join(" | ") || "never");
    for (const key of ["oneOf", "anyOf"] as const) {
      if (Array.isArray(s[key])) return wrap((s[key] as unknown[]).map((x) => this.print(x, depth + 1)).join(" | "));
    }
    if (Array.isArray(s["allOf"])) return wrap((s["allOf"] as unknown[]).map((x) => `(${this.print(x, depth + 1)})`).join(" & "));

    const type = s["type"];
    if (Array.isArray(type)) {
      return type.map((t) => this.print({ ...s, type: t, nullable: false }, depth + 1)).join(" | ");
    }
    switch (type) {
      case "string":
        return wrap(s["format"] === "binary" ? "Blob" : "string");
      case "integer":
      case "number":
        return wrap("number");
      case "boolean":
        return wrap("boolean");
      case "null":
        return "null";
      case "array":
        return wrap(`Array<${this.print(s["items"], depth + 1)}>`);
      case "object":
      case undefined: {
        const props = (s["properties"] ?? {}) as OpenApiDocument;
        const required = new Set((s["required"] as string[] | undefined) ?? []);
        const pad = "  ".repeat(depth + 1);
        const fields = Object.entries(props).map(
          ([k, v]) => `${pad}${prop(k)}${required.has(k) ? "" : "?"}: ${this.print(v, depth + 1)};`,
        );
        const extra = s["additionalProperties"];
        if (extra) fields.push(`${pad}[key: string]: ${extra === true ? "unknown" : this.print(extra, depth + 1)};`);
        if (fields.length === 0) return wrap(type === "object" ? "Record<string, unknown>" : "unknown");
        return wrap(`{\n${fields.join("\n")}\n${"  ".repeat(depth)}}`);
      }
      default:
        return "unknown";
    }
  }

  get document(): OpenApiDocument {
    return this.root;
  }
}

function jsonContent(container: OpenApiDocument | undefined): unknown {
  const content = container?.["content"] as Record<string, OpenApiDocument> | undefined;
  if (!content) return undefined;
  const key = Object.keys(content).find((k) => /json/i.test(k)) ?? Object.keys(content)[0];
  return key ? content[key]?.["schema"] : undefined;
}

export interface GenerateOptions {
  /** Module to import `EndpointDefinition` from. @default "got-api-engine" */
  importFrom?: string;
}

export function generateFromOpenApi(doc: OpenApiDocument, options: GenerateOptions = {}): string {
  const printer = new SchemaPrinter(doc);
  const out: string[] = [
    "// Generated by got-api-engine codegen — do not edit by hand.",
    "/* eslint-disable */",
    `import type { EndpointDefinition } from ${JSON.stringify(options.importFrom ?? "got-api-engine")};`,
    "",
  ];

  const schemas = ((doc["components"] as OpenApiDocument | undefined)?.["schemas"] ?? {}) as OpenApiDocument;
  for (const [name, schema] of Object.entries(schemas)) {
    const description = (schema as OpenApiDocument)["description"];
    if (typeof description === "string") out.push(`/** ${description.replace(/\*\//g, "*\\/")} */`);
    out.push(`export type ${pascal(name)} = ${printer.print(schema)};`, "");
  }

  const entries: string[] = [];
  const used = new Set<string>();
  const paths = (doc["paths"] ?? {}) as Record<string, OpenApiDocument>;
  for (const [rawPath, item] of Object.entries(paths)) {
    const shared = (item["parameters"] as OpenApiDocument[] | undefined) ?? [];
    for (const method of METHODS) {
      const op = item[method] as Operation | undefined;
      if (!op) continue;
      const path = rawPath.replace(/\{([^}]+)\}/g, ":$1");
      let name = camel(op.operationId ?? `${method} ${rawPath.replace(/[{}]/g, "")}`);
      while (used.has(name)) name += "_";
      used.add(name);

      const params = [...shared, ...(op.parameters ?? [])];
      const query = params.filter((p) => p["in"] === "query");
      const queryType = query.length
        ? `{ ${query.map((p) => `${prop(String(p["name"]))}${p["required"] ? "" : "?"}: ${printer.print(p["schema"])}`).join("; ")} }`
        : "Record<string, never>";

      const bodySchema = jsonContent(op.requestBody);
      const bodyType = bodySchema ? printer.print(bodySchema, 1) : "never";

      const responses = op.responses ?? {};
      const okKey = Object.keys(responses).find((k) => /^2\d\d$/.test(k));
      const okResponse = okKey ? responses[okKey] : undefined;
      const resSchema = jsonContent(okResponse);
      const resType = okKey === "204" ? "void" : resSchema ? printer.print(resSchema, 1) : "unknown";

      const typeName = pascal(name);
      out.push(`export type ${typeName}Response = ${resType};`);
      if (bodySchema) out.push(`export type ${typeName}Body = ${bodyType};`);
      out.push(`export type ${typeName}Query = ${queryType};`, "");

      const doc = op.summary ? `  /** ${op.summary.replace(/\*\//g, "*\\/")} */\n` : "";
      entries.push(
        `${doc}  ${name}: { method: ${JSON.stringify(method.toUpperCase())}, path: ${JSON.stringify(path)} } as EndpointDefinition<${JSON.stringify(path)}, ${typeName}Response, ${bodySchema ? `${typeName}Body` : "never"}, ${typeName}Query>,`,
      );
    }
  }

  out.push("export const endpoints = {", ...entries, "} as const;", "");
  return out.join("\n");
}
